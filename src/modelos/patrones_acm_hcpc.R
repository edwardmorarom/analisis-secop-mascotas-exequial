# ACM + HCPC (D97): comparación descriptiva con la tipología de clases latentes. Uso: Rscript patrones_acm_hcpc.R <numero de grupos>
suppressMessages(library(FactoMineR))
set.seed(2033)
args <- commandArgs(trailingOnly = TRUE)
k <- as.integer(args[1])
raiz <- normalizePath(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(FALSE), value = TRUE))), "..", ".."))
dir_res <- file.path(raiz, "data", "processed", "resultados_secop")
dir_out <- file.path(dir_res, "patrones")
b <- read.csv(file.path(dir_res, "patrones_base.csv"), stringsAsFactors = FALSE, colClasses = c(entidad_id = "character"))
comp <- c("inhumacion_cremacion", "traslado", "ataudes_bienes", "plan_exequial", "operacion_cementerio", "atencion_vulnerables_NN")
vars <- c("tipo_entidad", "modalidad_grupo", "tipo_contrato_hom", "orden_nivel", "cuartil_valor", comp)
x <- b[, vars]
for (v in comp) x[[v]] <- factor(ifelse(x[[v]] == 1, paste0(v, "_si"), paste0(v, "_no")))
for (v in setdiff(vars, comp)) x[[v]] <- factor(x[[v]])
acm <- MCA(x, ncp = 10, graph = FALSE)
hc <- HCPC(acm, nb.clust = k, graph = FALSE)
cl <- as.integer(hc$data.clust$clust)
write.csv(data.frame(grupo_hcpc = cl), file.path(dir_out, "acm_hcpc_grupos.csv"), row.names = FALSE)
inercia <- data.frame(dimension = seq_len(nrow(acm$eig)), autovalor = acm$eig[, 1], pct_varianza = acm$eig[, 2], pct_acumulado = acm$eig[, 3])
write.csv(head(inercia, 10), file.path(dir_out, "acm_inercia.csv"), row.names = FALSE)
print(table(cl)); print(head(inercia, 5))
